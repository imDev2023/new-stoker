#!/usr/bin/env python3
"""
The fonts a share card is set in (src/lib/ogFonts.ts), cut from the app's own faces in src/fonts.

A share card (each `opengraph-image.tsx`) is drawn by `next/og`, which lays text out with Satori: it reads TTF, OTF or
WOFF but neither WOFF2 nor a variable font's axes, and a Worker has no file system to read a font from at request time.
So each face the cards use is pinned here as a static instance of the site's variable files (Archivo semi-expanded and
heavy as the headlines set it, expanded and heavier for the lockup, Albert Sans for the copy), saved as TTF and written
into a TypeScript module as base64, which every bundler carries without a loader. Nothing is downloaded: the files and
their OFL licences are the ones the site serves. Each face keeps Google's two subsets, latin and latin-ext, as two
fonts the cards list in that order, so a letter the first lacks falls to the second.

Run it again when a card needs another face, weight or width, or when src/fonts changes:
`python3 apps/web/scripts/og-fonts.py` (it needs fontTools and brotli: `pip install fonttools brotli`).
"""
import base64
import sys
from io import BytesIO
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

WEB = Path(__file__).resolve().parent.parent
FONTS = WEB / "src" / "fonts"
OUT = WEB / "src" / "lib" / "ogFonts.ts"

# (name the cards ask for, weight Satori files it under, source file, axis values, letters to keep or None for all).
# The values are globals.css's: --font-display and --font-coin are 820 semi-expanded (112.5%), --font-brand 860
# expanded (125%); Satori matches weights in hundreds, so each instance is filed under the nearest one.
FACES = [
    ("Archivo", 800, "archivo-latin-wdth-normal.woff2", {"wght": 820, "wdth": 112.5}, None),
    ("Archivo Ext", 800, "archivo-latin-ext-wdth-normal.woff2", {"wght": 820, "wdth": 112.5}, None),
    ("Archivo Expanded", 800, "archivo-latin-wdth-normal.woff2", {"wght": 860, "wdth": 125}, "STKER"),
    ("Albert Sans", 500, "albert-sans-latin-wght-normal.woff2", {"wght": 500}, None),
    ("Albert Sans Ext", 500, "albert-sans-latin-ext-wght-normal.woff2", {"wght": 500}, None),
]


def instance(source: Path, axes: dict, letters: str | None) -> bytes:
    font = TTFont(source)
    font.flavor = None
    instantiateVariableFont(font, axes, inplace=True, updateFontNames=False)
    if letters is not None:
        options = subset.Options()
        # The copyright, the licence and the names stay in the file, as the Open Font License asks.
        options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
        options.notdef_outline = True
        subsetter = subset.Subsetter(options)
        subsetter.populate(text=letters)
        subsetter.subset(font)
    out = BytesIO()
    font.save(out)
    return out.getvalue()


def main() -> None:
    lines = [
        "// Generated by scripts/og-fonts.py from src/fonts: the share cards' faces as static instances, base64 so every",
        "// bundler carries them. Run the script again rather than editing this file.",
        "",
        "export type OgFont = { name: string; weight: 500 | 800; data: string };",
        "",
        "export const OG_FONTS: readonly OgFont[] = [",
    ]
    for name, weight, file, axes, letters in FACES:
        data = instance(FONTS / file, axes, letters)
        where = ", ".join(f"{k} {v}" for k, v in axes.items())
        print(f"{name}: {file} at {where}, {len(data):,} bytes", file=sys.stderr)
        lines.append(f"  // {file} at {where}{'' if letters is None else f', the letters {letters} only'}")
        lines.append(f'  {{ name: "{name}", weight: {weight}, data: "{base64.b64encode(data).decode("ascii")}" }},')
    lines += ["];", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({OUT.stat().st_size:,} bytes)", file=sys.stderr)


if __name__ == "__main__":
    main()
